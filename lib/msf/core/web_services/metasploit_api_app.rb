require 'rack/utils'
require 'securerandom'
require 'sinatra/base'
require 'swagger/blocks'
require 'warden'
require 'msf/core/web_services/authentication'
class Msf::WebServices::MetasploitApiApp < Sinatra::Base
  helpers Msf::WebServices::ServletHelper

  SETUP_TOKEN_HEADER = 'HTTP_X_MSF_SETUP_TOKEN'
  SETUP_TOKEN_FORMAT = /\A[0-9a-f]{64}\z/

  class << self
    # Whether this process has observed or created the initial user.
    attr_accessor :auth_initialized
  end

  # Loads the one-time setup token that msfdb writes for first-user bootstrap.
  #
  # @return [String, nil] the token, or nil when no token file is configured or the file is
  #   not a regular, private file containing exactly one 64-character lowercase hex token.
  def self.load_setup_token
    path = ENV['MSF_WS_SETUP_TOKEN_FILE']
    return nil if path.nil? || path.empty?
    raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must be an absolute path' unless path == File.expand_path(path)

    stat = File.lstat(path)
    raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must not be a symlink' if stat.symlink?
    raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must be a regular file' unless stat.file?

    unless Gem.win_platform?
      raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must be owned by the service user' unless stat.uid == Process.uid
      raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must have mode 0600' unless (stat.mode & 0o777) == 0o600
    end

    open_flags = File::RDONLY | File::BINARY
    open_flags |= File::NOFOLLOW if !Gem.win_platform? && defined?(File::NOFOLLOW)

    token = nil
    File.open(path, open_flags) do |file|
      opened_stat = file.stat
      unchanged = opened_stat.file? &&
                  opened_stat.dev == stat.dev &&
                  opened_stat.ino == stat.ino &&
                  opened_stat.size == stat.size &&
                  opened_stat.mtime == stat.mtime
      raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE changed while it was being opened' unless unchanged

      unless Gem.win_platform?
        raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must be owned by the service user' unless opened_stat.uid == Process.uid
        raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must have mode 0600' unless (opened_stat.mode & 0o777) == 0o600
      end

      token = file.read(65)
    end

    unless token.is_a?(String) && SETUP_TOKEN_FORMAT.match?(token)
      raise ArgumentError, 'MSF_WS_SETUP_TOKEN_FILE must contain exactly one 64-character lowercase hex token'
    end

    token
  rescue StandardError => e
    warn("Failed to load MSF web service setup token: #{e.message}")
    nil
  end

  # Servlet registration
  register Msf::WebServices::ReadinessServlet
  register Msf::WebServices::ApiDocsServlet
  register Msf::WebServices::AuthServlet
  register Msf::WebServices::HostServlet
  register Msf::WebServices::VulnServlet
  register Msf::WebServices::EventServlet
  register Msf::WebServices::WebServlet
  register Msf::WebServices::MsfServlet
  register Msf::WebServices::NoteServlet
  register Msf::WebServices::WorkspaceServlet
  register Msf::WebServices::ServiceServlet
  register Msf::WebServices::SessionServlet
  register Msf::WebServices::ExploitServlet
  register Msf::WebServices::LootServlet
  register Msf::WebServices::SessionEventServlet
  register Msf::WebServices::CredentialServlet
  register Msf::WebServices::LoginServlet
  register Msf::WebServices::NmapServlet
  register Msf::WebServices::DbExportServlet
  register Msf::WebServices::VulnAttemptServlet
  register Msf::WebServices::UserServlet
  register Msf::WebServices::PayloadServlet
  register Msf::WebServices::ModuleSearchServlet
  register Msf::WebServices::DbImportServlet
  register Msf::WebServices::RouteServlet

  configure do
    set :sessions, {key: 'msf-ws.session', expire_after: 300}
    set :session_secret, ENV.fetch('MSF_WS_SESSION_SECRET') { SecureRandom.hex(32) }
    # The setup token is only read from an absolute path in MSF_WS_SETUP_TOKEN_FILE.
    # It is generated by msfdb for the duration of first-user bootstrap, then removed.
    set :setup_token, load_setup_token
    # Sinatra 4 / rack-protection 4.x enables host authorization by default;
    # the web service binds to user-specified addresses so all hosts are permitted.
    set :host_authorization, { permitted_hosts: [] }
  end

  before do
    # Remove the setup token immediately so it cannot be retained in the Rack environment
    # if a later database lookup fails.
    setup_token = request.env.delete(SETUP_TOKEN_HEADER)

    # Readiness must work while the database is unavailable, so it must not access the
    # DBManager or the users table before the route has a chance to report unhealthy.
    unless readiness_request?
      # store DBManager in request environment so that it is available to Warden
      request.env['msf.db_manager'] = get_db
      # Once a user exists the flag latches on for the lifetime of the process.
      self.class.auth_initialized ||= get_db.users({}).count > 0

      # While no users exist an initial account has to be creatable before any credentials
      # exist. The request must also prove it came from msfdb by presenting the one-time setup
      # token. The exemption is limited to that one route, so a database that reports no users
      # for any other reason - an empty database restored under the service, a failover onto a
      # fresh instance - cannot expose the rest of the API unauthenticated.
      request.env['msf.bootstrap'] = initial_account_creation? &&
                                     !self.class.auth_initialized &&
                                     valid_setup_token?(setup_token)
      request.env['msf.auth_initialized'] = self.class.auth_initialized || !initial_account_creation?
    end
  end

  use Warden::Manager do |config|
    # failed authentication is handled by this application
    config.failure_app = self
    # don't intercept 401 responses since the app will provide custom failure messages
    config.intercept_401 = false
    config.default_scope = :api

    config.scope_defaults :user,
                          # whether to persist the result in the session or not
                          store: true,
                          # list of strategies to use
                          strategies: [:password],
                          # action (route) of the failure application
                          action: "#{Msf::WebServices::AuthServlet.api_unauthenticated_path}/user"

    config.scope_defaults :api,
                          # whether to persist the result in the session or not
                          store: false,
                          # list of strategies to use
                          strategies: [:api_token],
                          # action (route) of the failure application
                          action: Msf::WebServices::AuthServlet.api_unauthenticated_path

    config.scope_defaults :admin_api,
                          # whether to persist the result in the session or not
                          store: false,
                          # list of strategies to use
                          strategies: [:admin_api_token],
                          # action (route) of the failure application
                          action: Msf::WebServices::AuthServlet.api_unauthenticated_path
  end

  # Whether the request is the one that creates a user account, which is the only request
  # permitted to run unauthenticated before any account exists.
  #
  # @return [Boolean] true if the request creates a user account; otherwise, false.
  def initial_account_creation?
    request.post? && request.path_info.chomp('/') == Msf::WebServices::UserServlet.api_path
  end

  # Whether the request is the unauthenticated database readiness probe.
  #
  # @return [Boolean] true if the request is a readiness probe; otherwise, false.
  def readiness_request?
    request.get? && request.path_info.chomp('/') == Msf::WebServices::ReadinessServlet.api_path
  end

  # Compares a submitted setup token with the configured token after validating both formats.
  #
  # @param submitted_token [Object] the value of the setup-token header.
  # @return [Boolean] true if the submitted token is valid; otherwise, false.
  def valid_setup_token?(submitted_token)
    expected_token = settings.setup_token
    return false unless submitted_token.is_a?(String) && expected_token.is_a?(String)
    return false unless SETUP_TOKEN_FORMAT.match?(submitted_token) && SETUP_TOKEN_FORMAT.match?(expected_token)

    Rack::Utils.secure_compare(expected_token, submitted_token)
  end

  # Records that the initial account has been created so the bootstrap token cannot be reused.
  def mark_auth_initialized!
    self.class.auth_initialized = true
    settings.setup_token = nil
  end

end
